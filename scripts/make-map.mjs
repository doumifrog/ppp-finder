import fs from 'fs';
import {feature} from 'topojson-client';
import {geoPath, geoConicConformal} from 'd3-geo';
const t=JSON.parse(fs.readFileSync('node_modules/us-atlas/counties-10m.json'));
const fc=feature(t,t.objects.counties);
const co={type:'FeatureCollection',features:fc.features.filter(f=>f.id.startsWith('08'))};
const W=760,H=560;
const proj=geoConicConformal().parallels([38.45,39.75]).rotate([105.5,0]).fitSize([W,H],co);
const p=geoPath(proj).digits(1);
const out=co.features.map(f=>{const [x,y]=p.centroid(f);return {n:f.properties.name,d:p(f),x:+x.toFixed(1),y:+y.toFixed(1)}}).sort((a,b)=>a.n.localeCompare(b.n));
console.log(out.length);
fs.writeFileSync('../co_counties.json',JSON.stringify(out));
import {neighbors} from 'topojson-client';
const geoms=t.objects.counties.geometries;
const nb=neighbors(geoms);
const adj={};
geoms.forEach((g,i)=>{if(!g.id.startsWith('08'))return;adj[g.properties.name]=nb[i].filter(j=>geoms[j].id.startsWith('08')).map(j=>geoms[j].properties.name).sort();});
fs.writeFileSync('../co_adj.json',JSON.stringify(adj));
console.log(adj['Baca'],adj['Denver']);
